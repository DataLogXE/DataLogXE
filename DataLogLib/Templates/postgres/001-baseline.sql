-- Measurement archive. Every compression level (raw and the M4 levels C001 to C3600) has its own hypertable, so chunk
-- size, compression delay and retention fit the density of the level. Uncompressed rows take about 20 times the space
-- of compressed ones (on a Raspberry Pi archive ~103 B against ~5 B per value), so the chunks are compressed shortly
-- after they close. The chunks of the fine levels are about as large uncompressed as a chunk of the raw values (2 300
-- values/s on the Pi); archiveraw keeps 30 minutes, the index of a longer open chunk would no longer fit into the
-- shared buffers of the Pi (128 MB).

-- The archive keeps the data tag uid, ids are only unique per configuration database
CREATE TABLE archivetag (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    guid text NOT NULL UNIQUE
);


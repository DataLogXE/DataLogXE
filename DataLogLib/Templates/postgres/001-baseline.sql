-- Hourly counts of every alarm in every state, for the statistics of the alarm details. ProcessEventStore counts the
-- points it writes in the same transaction; the rows that were there before (id below live_from_id) are counted once
-- by ProcessEventCountWorker, from the newest hour back (backfill_before is how far it got).
--
-- The alarm of a point, as AlarmTracker keys its conditions: a system alarm by the source it reports on and its type,
-- a process alarm by its condition id, else its source and condition name, else its message. The values are taken as
-- they stand in the props JSON, which can be cut and so is no valid JSON; the same serializer writes every row. A value
-- ends at the next "," (a quote inside it is escaped), or with the rest of the props for the last key. split_part
-- instead of a regex: 0.3 instead of 10 us a row on the Mac, the backfill runs it on every row once.
CREATE FUNCTION processevent_condition_hash(component text, affected_source_id integer, event_type text, props text, message text)
RETURNS bigint LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
SELECT ('x' || left(encode(sha256(convert_to(
    CASE WHEN component = 'system_alarm' THEN 'system|' || affected_source_id || '|' || COALESCE(event_type, '')
    ELSE COALESCE(
        'condition|' || NULLIF(split_part(split_part(props, '"ConditionId":"', 2), '","', 1), ''),
        'name|' || NULLIF(split_part(split_part(props, '"SourceName":"', 2), '","', 1)
            || '|' || split_part(split_part(props, '"ConditionName":"', 2), '","', 1), '|'),
        'message|' || COALESCE(message, ''))
    END, 'UTF8')), 'hex'), 16))::bit(64)::bigint
$$;

